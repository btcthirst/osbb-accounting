package repository

import (
	"errors"
	"osbb-accounting/domain"
)

// Помилки, що можуть виникнути при роботі з UserRepository.
// Ці помилки використовуються для абстракції від конкретної реалізації БД
// і забезпечують єдиний інтерфейс обробки помилок на рівні сервісів.
var (
	// ErrUserNotFound повертається, коли користувача не знайдено в БД
	ErrUserNotFound = errors.New("користувача не знайдено")

	// ErrUserAlreadyExists повертається при спробі створити користувача
	// зUsername, що вже існує (порушення унікальності)
	ErrUserAlreadyExists = errors.New("користувач з таким іменем вже існує")

	// ErrInvalidUserID повертається при спробі операції з невалідним ID
	ErrInvalidUserID = errors.New("невалідний ID користувача")

	// ErrDatabaseConnection повертається при проблемах з підключенням до БД
	ErrDatabaseConnection = errors.New("помилка з'єднання з базою даних")

	// ErrTransactionFailed повертається при невдалій транзакції
	ErrTransactionFailed = errors.New("помилка виконання транзакції")
)

// UserRepository визначає контракт (інтерфейс) для всіх операцій
// з користувачами в системі. Це ключовий елемент DAO/Repository Pattern.
//
// КРИТИЧНО: Жодна бізнес-логіка (service layer) не повинна мати прямого
// доступу до database/sql чи SQLite драйверів. Весь доступ до даних
// здійснюється ВИКЛЮЧНО через цей інтерфейс.
//
// Переваги цього підходу:
//   - Легка міграція з SQLite на PostgreSQL (тільки змінюємо імплементацію)
//   - Можливість мокування для юніт-тестів
//   - Чітке розділення відповідальностей (Separation of Concerns)
//   - Незалежність бізнес-логіки від деталей реалізації БД
type UserRepository interface {
	// SaveUser зберігає нового користувача в БД.
	// Автоматично генерує ID та встановлює CreatedAt, UpdatedAt.
	//
	// Параметри:
	//   - user: вказівник на domain.User для збереження
	//
	// Повертає:
	//   - error: nil при успіху, ErrUserAlreadyExists якщо Username зайнятий,
	//            інші помилки при проблемах з БД
	//
	// Після успішного збереження поле user.ID буде заповнене
	// згенерованим ідентифікатором.
	SaveUser(user *domain.User) error

	// FindByID знаходить користувача за його унікальним ідентифікатором.
	//
	// Параметри:
	//   - id: унікальний ідентифікатор користувача
	//
	// Повертає:
	//   - *domain.User: знайденого користувача
	//   - error: nil при успіху, ErrUserNotFound якщо не знайдено,
	//            інші помилки при проблемах з БД
	FindByID(id int) (*domain.User, error)

	// FindByUsername знаходить користувача за унікальним іменем для входу.
	// Використовується в процесі аутентифікації.
	//
	// Параметри:
	//   - username: унікальне ім'я користувача (case-sensitive)
	//
	// Повертає:
	//   - *domain.User: знайденого користувача
	//   - error: nil при успіху, ErrUserNotFound якщо не знайдено,
	//            інші помилки при проблемах з БД
	FindByUsername(username string) (*domain.User, error)

	// FindAll повертає список всіх активних користувачів у системі.
	// Використовується для адміністративних інтерфейсів.
	//
	// Повертає:
	//   - []*domain.User: слайс користувачів (може бути порожнім)
	//   - error: nil при успіху, помилки при проблемах з БД
	FindAll() ([]*domain.User, error)

	// FindByRole знаходить всіх користувачів з вказаною роллю.
	// Корисно для відображення списків бухгалтерів, адміністраторів тощо.
	//
	// Параметри:
	//   - role: роль для фільтрації (одна з констант domain.Role*)
	//
	// Повертає:
	//   - []*domain.User: слайс користувачів з вказаною роллю
	//   - error: nil при успіху, помилки при проблемах з БД
	FindByRole(role string) ([]*domain.User, error)

	// UpdateUser оновлює існуючого користувача в БД.
	// Автоматично оновлює поле UpdatedAt.
	//
	// Параметри:
	//   - user: вказівник на domain.User з оновленими даними (ID обов'язковий)
	//
	// Повертає:
	//   - error: nil при успіху, ErrUserNotFound якщо користувача не існує,
	//            ErrUserAlreadyExists якщо новий Username зайнятий,
	//            інші помилки при проблемах з БД
	UpdateUser(user *domain.User) error

	// UpdateRole змінює роль користувача.
	// Окремий метод для підвищення безпеки (лог зміни ролей).
	//
	// Параметри:
	//   - id: ідентифікатор користувача
	//   - role: нова роль (одна з констант domain.Role*)
	//
	// Повертає:
	//   - error: nil при успіху, ErrUserNotFound якщо користувача не існує,
	//            помилки валідації ролі, інші помилки при проблемах з БД
	UpdateRole(id int, role string) error

	// UpdatePassword оновлює хешований пароль користувача.
	// Окремий метод для підвищення безпеки.
	//
	// Параметри:
	//   - id: ідентифікатор користувача
	//   - hashedPassword: новий хешований пароль (BCrypt)
	//
	// Повертає:
	//   - error: nil при успіху, ErrUserNotFound якщо користувача не існує,
	//            інші помилки при проблемах з БД
	UpdatePassword(id int, hashedPassword string) error

	// DeactivateUser виконує "м'яке" видалення користувача.
	// Встановлює IsActive = false замість фізичного видалення з БД.
	// Це дозволяє зберегти історичні дані про платежі та операції.
	//
	// Параметри:
	//   - id: ідентифікатор користувача для деактивації
	//
	// Повертає:
	//   - error: nil при успіху, ErrUserNotFound якщо користувача не існує,
	//            інші помилки при проблемах з БД
	DeactivateUser(id int) error

	// ActivateUser активує раніше деактивованого користувача.
	//
	// Параметри:
	//   - id: ідентифікатор користувача для активації
	//
	// Повертає:
	//   - error: nil при успіху, ErrUserNotFound якщо користувача не існує,
	//            інші помилки при проблемах з БД
	ActivateUser(id int) error

	// DeletePermanently виконує фізичне видалення користувача з БД.
	// УВАГА: Використовувати тільки в крайніх випадках, оскільки
	// це може порушити цілісність історичних даних.
	//
	// Параметри:
	//   - id: ідентифікатор користувача для видалення
	//
	// Повертає:
	//   - error: nil при успіху, ErrUserNotFound якщо користувача не існує,
	//            інші помилки при проблемах з БД
	DeletePermanently(id int) error
}
